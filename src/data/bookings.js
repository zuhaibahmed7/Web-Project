import { isoFromToday } from '../utils/date';
import { STATUS, STATUS_META } from '../utils/booking';

function at(daysAgo, time = '10:00') {
  return `${isoFromToday(-daysAgo)}T${time}:00.000Z`;
}

// Build a timeline from the steps a booking has actually passed through.
function tl(steps) {
  return steps.map(([status, daysAgo, by]) => ({ status, at: at(daysAgo), by }));
}

