// Notifications are generated from the booking history at seed time, then added
// to whenever a status changes at runtime.
export function buildSeedNotifications(bookings, users, providers) {
  // Providers are linked to their login account through user.providerId.
  const ownerOf = new Map();
  users.forEach((u) => {
    if (u.role === 'provider' && u.providerId) ownerOf.set(u.providerId, u.id);
  });

  const nameOf = (userId) => users.find((u) => u.id === userId)?.name ?? 'Customer';
  const providerName = (id) => providers.find((p) => p.id === id)?.name ?? 'Provider';

  const out = [];
  let n = 0;

  bookings.forEach((b) => {
    b.timeline.forEach((step) => {
      n += 1;
      // Provider/admin actions notify the customer; customer actions notify the provider.
      const notifyCustomer = step.by === 'provider' || step.by === 'admin';
      const recipient = notifyCustomer ? b.customerId : ownerOf.get(b.providerId) ?? b.customerId;
      const label = STATUS_META[step.status]?.label ?? step.status;

      out.push({
        id: `nt-${n}`,
        userId: recipient,
        kind: 'booking',
        bookingId: b.id,
        read: new Date(b.updatedAt).getTime() < Date.now() - 3 * 86400000,
        createdAt: step.at,
        title: `${b.code} · ${label}`,
        message: notifyCustomer
          ? `${providerName(b.providerId)} updated booking ${b.code} to "${label}".`
          : `New booking ${b.code} from ${nameOf(b.customerId)} — ${label}.`,
      });
    });
  });

  return out.sort((a, b) => new Date(b.createdAt) - new Date(a.createdAt));
}
