// Keys are flat and dot-namespaced ("home.ctaBody") because the lookup is a
// single object read per string. Missing keys fall back to English, then to the
// fallback passed by the caller — so a page can stay half-translated without
// ever rendering "home.ctaBody" to a visitor.
//
// Scope note: signed-in dashboards and the admin console stay English by design.
// Seed content (business names, bios, service titles, reviews) is user-generated
// data and is never translated either — a real marketplace would not rewrite a
// provider's own words.
//
// {placeholders} are interpolated by t(); digits stay in Latin numerals because
// that is what Pakistani interfaces do in practice.

